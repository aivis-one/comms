import json
import re
import tomllib
from pathlib import Path
from typing import Any

import pytest

from app.api.prefs import PeriodIn, PreferencesPatch

_ROOT = Path(__file__).resolve().parent.parent
_PYPROJECT_TEXT = (_ROOT / "pyproject.toml").read_text()
_PYPROJECT = tomllib.loads(_PYPROJECT_TEXT)

# THE TWO LOCKS (W1-1): the runtime's, `dependencies` only, and the dev
# one, `dependencies` + `dev` -- what each is for and how both are made is
# written once, in pyproject.toml above [project.optional-dependencies].
_RUNTIME_LOCK = "requirements.lock"
_DEV_LOCK = "requirements-dev.lock"
_LOCKS = {
    name: (_ROOT / name).read_text() for name in (_RUNTIME_LOCK, _DEV_LOCK)
}
# The command each lock is the output of -- uv writes it as the file's
# second line; pyproject.toml records the two joined, in this order.
_COMMANDS = {
    _DEV_LOCK: (
        "uv pip compile pyproject.toml --extra dev --python-version 3.12 "
        "--generate-hashes -o requirements-dev.lock"
    ),
    _RUNTIME_LOCK: (
        "uv pip compile pyproject.toml --python-version 3.12 "
        "--generate-hashes -c requirements-dev.lock -o requirements.lock"
    ),
}
_UV_FIRST_LINE = "# This file was autogenerated by uv via the following command:"


def _requirement_name(spec: str) -> str:
    """The distribution name out of a requirement string."""
    return re.split(r"[><=!~\[ ]", spec, maxsplit=1)[0].strip().lower()


def _names(specs: list[str]) -> set[str]:
    return {_requirement_name(spec).replace("_", "-") for spec in specs}


def _declared(lock: str) -> set[str]:
    """What `lock` must cover: the runtime lock `dependencies`, the dev
    lock `dependencies` and `dev`."""
    project = _PYPROJECT["project"]
    names = _names(list(project["dependencies"]))
    if lock == _DEV_LOCK:
        names |= _names(list(project["optional-dependencies"]["dev"]))
    return names


def _locked_distributions(text: str) -> set[str]:
    names = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        names.add(line.split("==", 1)[0].strip().lower().replace("_", "-"))
    return names


_STANZA = re.compile(
    r"^(?P<name>[A-Za-z0-9_.\-]+)==(?P<version>[^\s\\;]+)"
    r"(?P<hashes>(?:[ \t]*\\\n[ \t]+--hash=sha256:[0-9a-f]{64})*)",
    re.M,
)


def _stanzas(text: str) -> dict[str, tuple[str, frozenset[str]]]:
    """name -> (version, its hashes), one entry per pinned package. A name
    pinned twice is refused, not read as its last stanza: a hand edit can
    leave two, and a dict would keep one of them silently."""
    found: dict[str, tuple[str, frozenset[str]]] = {}
    for match in _STANZA.finditer(text):
        name = match["name"].lower().replace("_", "-")
        assert name not in found, f"{name} is pinned twice"
        found[name] = (
            match["version"],
            frozenset(re.findall(r"sha256:([0-9a-f]{64})", match["hashes"])),
        )
    return found


def _disagreeing(
    runtime: dict[str, tuple[str, frozenset[str]]],
    dev: dict[str, tuple[str, frozenset[str]]],
) -> list[str]:
    """The packages of the runtime lock the dev lock pins otherwise -- by
    version or by artifact -- or does not pin at all."""
    return sorted(name for name, pin in runtime.items() if dev.get(name) != pin)


def _recorded_command(text: str) -> str:
    """pyproject.toml's REGENERATE command: the indented comment lines
    after it, continuations joined."""
    block = text.split("# REGENERATE", 1)[1].split("\n#\n", 2)[1]
    lines = [line.lstrip("#").strip() for line in block.splitlines()]
    return " ".join(" ".join(lines).replace("\\", " ").split())


_EVERY_DECLARED = [
    (lock, name) for lock in _LOCKS for name in sorted(_declared(lock))
]


class TestTheLockCoversWhatIsDeclared:
    """The image and CI install from the two locks, not from the ranges
    in pyproject. A dependency added to pyproject and not regenerated
    into its lock does not fail the build -- it fails at import, in the
    container, later.

    Until W1-1 one lock carried prod and dev both, because the runtime
    image ran the suite; the runtime image runs no test now, so each
    lock covers its own part of pyproject, and every check here is made
    on both files.
    """

    @pytest.mark.parametrize("lock, name", _EVERY_DECLARED)
    def test_every_declared_dependency_is_pinned(self, lock: str, name: str) -> None:
        assert name in _locked_distributions(_LOCKS[lock]), (
            f"{name} is declared in pyproject and absent from {lock} -- "
            f"regenerate the locks in this commit (the command is in "
            f"pyproject.toml)"
        )

    @pytest.mark.parametrize("lock, name", _EVERY_DECLARED)
    def test_every_pinned_line_carries_a_hash(self, lock: str, name: str) -> None:
        """A version pin says WHICH release; a hash says which ARTIFACT.

        The guard exists because losing the hashes costs nothing
        visible: regenerate without --generate-hashes and the file
        still installs, still pins every version, and quietly stops
        checking what was downloaded. Nothing fails, so nothing tells
        anyone -- the same shape as a comment that points at a file
        that no longer exists.
        """
        lines = _LOCKS[lock].splitlines()
        for position, line in enumerate(lines):
            head = line.split("==")[0].strip().lower().replace("_", "-")
            if "==" in line and not line.startswith("#") and head == name:
                rest = "\n".join(lines[position:position + 40])
                assert "--hash=sha256:" in rest.split("\n")[1], (
                    f"{name} is pinned in {lock} without a hash -- the lock "
                    f"was regenerated without --generate-hashes (the command "
                    f"is in pyproject.toml)"
                )
                return
        pytest.fail(f"{name} is not in {lock} at all")

    @pytest.mark.parametrize("lock", list(_LOCKS))
    def test_every_stanza_carries_a_hash(self, lock: str) -> None:
        """Every package of the file, not only the declared ones: a
        transitive package without a hash is installed unchecked just
        the same -- and under --require-hashes it fails the build."""
        stanzas = _stanzas(_LOCKS[lock])
        assert stanzas.keys() == _locked_distributions(_LOCKS[lock])
        assert [name for name, (_, hashes) in stanzas.items() if not hashes] == []

    @pytest.mark.parametrize("lock", list(_LOCKS))
    def test_the_hashes_cover_more_than_one_artifact(self, lock: str) -> None:
        """THE PAIR to the line-by-line check: a file where every
        package carries exactly one hash would satisfy it and would
        pin comms to one platform's wheel -- an image built on another
        architecture could then not be installed at all. Packages with
        compiled wheels carry a hash per artifact.
        """
        hashes = _LOCKS[lock].count("--hash=sha256:")
        assert hashes > len(_locked_distributions(_LOCKS[lock])) * 2

    @pytest.mark.parametrize("lock", list(_LOCKS))
    def test_everything_in_the_lock_is_pinned_exactly(self, lock: str) -> None:
        """A lock with a range in it is not a lock. The pair to the
        coverage test above: coverage is satisfied by a file that
        merely names the packages."""
        text = _LOCKS[lock]
        loose = [
            line.strip()
            for line in text.splitlines()
            if line.strip()
            and not line.startswith("#")
            and not line.startswith(" ")
            and not line.strip().startswith("--hash")
            and "==" not in line
        ]
        assert loose == []
        assert len(_locked_distributions(text)) > len(_declared(lock))


class TestTheTwoLocksAreOneResolution:
    """W1-1: two files, one resolution. The runtime lock is resolved
    under the dev lock as a constraint, so a package both carry is one
    release and one set of artifacts -- what the suite ran against in the
    test stage is what the runtime image installs. Held here, because a
    file regenerated alone, or edited by hand, still installs."""

    def test_the_shared_packages_are_pinned_alike(self) -> None:
        runtime = _stanzas(_LOCKS[_RUNTIME_LOCK])
        dev = _stanzas(_LOCKS[_DEV_LOCK])
        # The pair: both read, the runtime's packages a part of the dev
        # lock's, and the dev lock larger by the tools.
        assert len(runtime) > 30, len(runtime)
        assert runtime.keys() < dev.keys()
        assert _disagreeing(runtime, dev) == []

    def test_the_guard_sees_a_drift(self) -> None:
        dev = _stanzas(_LOCKS[_DEV_LOCK])
        version, hashes = dev["fastapi"]
        moved = {"fastapi": ("0.0.1", hashes)}
        other = {"fastapi": (version, frozenset({"0" * 64}))}
        assert _disagreeing(moved, dev) == ["fastapi"]
        assert _disagreeing(other, dev) == ["fastapi"]
        assert _disagreeing({"fastapi": dev["fastapi"]}, dev) == []

    def test_a_package_pinned_twice_is_refused(self) -> None:
        stanza = "a==1.0 \\\n    --hash=sha256:" + "1" * 64 + "\n"
        with pytest.raises(AssertionError, match="pinned twice"):
            _stanzas(stanza + stanza)
        assert _stanzas(stanza) == {"a": ("1.0", frozenset({"1" * 64}))}

    @pytest.mark.parametrize("lock", list(_LOCKS))
    def test_each_lock_is_the_output_of_the_recorded_command(
        self, lock: str,
    ) -> None:
        """The file is the command's output, whole: uv writes its own
        first two lines, the command that made the file; a header added
        by hand would be erased by the next regeneration (until W1-1
        the lock carried one, and the command in it erased it)."""
        first, second = _LOCKS[lock].splitlines()[:2]
        assert first == _UV_FIRST_LINE
        assert second == f"#    {_COMMANDS[lock]}"

    def test_pyproject_records_the_one_command(self) -> None:
        """Both files from one command, the dev lock first -- the runtime
        lock's resolution is constrained by it."""
        assert _recorded_command(_PYPROJECT_TEXT) == (
            f"{_COMMANDS[_DEV_LOCK]} && {_COMMANDS[_RUNTIME_LOCK]}"
        )


class TestTheSeamsNameTheStreams:
    """The stream and the group are half of an agreement.

    A relay pointing at a name nobody reads is not an error on either
    side: it writes into a stream with no consumer, and the
    notifications simply never arrive. The names are defaulted, so the
    deploy works without them -- which is exactly why they have to be
    written down, or the other side has to read our source to learn
    what to match.

    Was TestTheTemplatesCarryTheContract: the names were held in the
    deploy's template of the environment, until LEG-1 took the template
    out. The product reads them in INTEGRATION.md section 15 (the seams,
    "The stream names are fixed"), held here to the code both ways: each
    name the paragraph gives is the setting's default, and each default
    is in the paragraph.
    """

    @staticmethod
    def _paragraph() -> str:
        text = (_ROOT / "deploy" / "INTEGRATION.md").read_text()
        section = text[text.index("## 15. The seams"):]
        start = section.index("**The stream names are fixed.**")
        return " ".join(section[start:section.index("\n\n", start)].split())

    @pytest.mark.parametrize(
        ("phrase", "field"),
        [
            ("XADDs into the stream `{}`", "comms_events_stream"),
            ("as its consumer group `{}`", "comms_consumer_group"),
        ],
    )
    def test_the_paragraph_names_the_default(
        self, phrase: str, field: str,
    ) -> None:
        from app.core.config import Settings

        default = Settings.model_fields[field].default
        assert default  # the pair: there is a name to match
        paragraph = self._paragraph()
        assert phrase.format(default) in paragraph, (field, paragraph)

    def test_the_paragraph_names_nothing_else(self) -> None:
        """The other way: every name in backticks in the paragraph is
        one of the two defaults -- a name the code does not default to
        would send an integrator to a stream nobody reads."""
        from app.core.config import Settings

        defaults = {
            Settings.model_fields[field].default
            for field in ("comms_events_stream", "comms_consumer_group")
        }
        named = set(re.findall(r"`([^`]+)`", self._paragraph()))
        assert named == defaults


